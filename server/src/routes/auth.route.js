const express = require('express');
const {
  register,
  login,
  getProfile,
  updateProfile,
  changePassword,
  refreshToken,
  getAllUsers,
  deleteUser
} = require('../controllers/auth.controller');
const { auth, authorizeRoles } = require('../middlewares/authMiddleware');

const router = express.Router();

